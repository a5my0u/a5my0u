"""Generate the English profile from the reviewed configuration.

Default references local, real generated images. Switch to profile-assets only
after that branch has been seeded successfully during an approved deployment.
"""
from __future__ import annotations
import argparse
from datetime import date
from html import escape
import json
from pathlib import Path
import re
try:
    from .svg_utils import start, text
except ImportError:
    from svg_utils import start, text

ROOT = Path(__file__).resolve().parents[1]
TECH_FILES = ['programming-languages', 'data-science-ai', 'web-database', 'development-tools']

def date_label(value):
    return date.fromisoformat(value+'-01').strftime('%b %Y')

def about_cards(config, root):
    p = config['palette']
    cert = config['about']['certification']
    cards = [
        ('focus', 'FOCUS', config['about']['focus']),
        ('learning', 'CURRENTLY LEARNING', config['about']['learning']),
        ('certification', 'CERTIFICATION', [cert['name'], cert['level']])
    ]
    folder = root/'assets/about'
    folder.mkdir(parents=True, exist_ok=True)
    for slug, label, lines in cards:
        value = start(360, 174, label.title(), '. '.join(lines), p['card'])
        value += f'<rect x=".5" y=".5" width="359" height="173" rx="18" fill="none" stroke="{p["border"]}"/>'
        value += text(24, 39, label, 16, p['muted'], 500)
        if slug == 'certification':
            value += text(24, 81, 'Japan Statistical Society', 19, p['text']) + text(24, 108, 'Certificate', 19, p['text']) + text(24, 145, cert['level'], 25, p['accent'], 500)
        else:
            value += text(24, 86, lines[0], 24, p['text'], 500)
            if slug == 'learning':
                for index, line in enumerate(lines[1:3]):
                    value += text(24, 119 + index * 29, line, 20, p['text'])
            else:
                value += text(24, 121, lines[1], 24, p['text'], 500)
        (folder/(slug+'.svg')).write_text(value+'</svg>', encoding='utf-8')

def render(config, generated_branch=None):
    if generated_branch and not re.fullmatch(r'[A-Za-z0-9_-]+', generated_branch):
        raise ValueError('Invalid generated branch')
    base = './assets/generated/' if not generated_branch else f"https://raw.githubusercontent.com/{config['repository']}/{generated_branch}/assets/generated/"
    a = config['about']
    lines = [
        '<!-- Generated by scripts/generate_readme.py from config/profile.json. -->',
        '<picture>',
        '  <source media="(prefers-reduced-motion: reduce) and (max-width: 600px)" srcset="./assets/header/header-mobile-static.svg" />',
        '  <source media="(prefers-reduced-motion: reduce)" srcset="./assets/header/header-static.svg" />',
        '  <source media="(max-width: 600px)" srcset="./assets/header/header-mobile.svg" />',
        f'  <img src="./assets/header/header.svg" alt="{escape(config["username"])} — Data Science / Engineering. Machine Learning, AI and Software. Chiba University, Japan." width="1200" />',
        '</picture>', '',
        '<details><summary>Static header</summary>', '',
        '<img src="./assets/header/header-static.svg" alt="Static Dark Silk profile header" width="1200" />', '', '</details>', '',
        '## 01 / ABOUT ME', '', a['intro'], '', a['body'], '',
        '<p>',
        '  <img src="./assets/about/focus.svg" alt="Focus: Machine Learning and Data Science" width="270" />',
        '  <img src="./assets/about/learning.svg" alt="Currently learning: Deep Learning, Machine Learning and AI Engineering" width="270" />',
        '  <a href="https://www.toukei-kentei.jp/faq"><img src="./assets/about/certification.svg" alt="Japan Statistical Society Certificate, Grade 2" width="270" /></a>',
        '</p>', '',
        '## 02 / TECH STACK', '', '<p>'
    ]
    for (label, names), filename in zip(config['tech_stack'].items(), TECH_FILES):
        lines.append(f'  <img src="./assets/tech/{filename}.svg" alt="{escape(label)}: {escape(", ".join(names))}" width="410" />')
    lines += ['</p>', '', '## 03 / EXPERIENCE', '']
    for experience in config['experience']:
        if not experience.get('publish') or experience.get('confirmation_required'):
            continue
        start_date = date.fromisoformat(experience['start']+'-01')
        if start_date > date.today():
            raise ValueError('Future internships cannot be published as experience')
        period = date_label(experience['start'])
        if experience['end'] != experience['start']:
            period += ' – ' + (date_label(experience['end']) if experience['end'] else 'Present')
        lines += ['### '+experience['role'], '', '*'+period+'*', '']
        lines.extend('- '+item for item in experience['details'])
        lines.append('')
    if config.get('achievement', {}).get('publish') and not config['achievement'].get('confirmation_required'):
        lines += ['**Selected achievement**', '', config['achievement']['text'], '']
    projects = config.get('featured_projects', [])
    if projects:
        lines += ['## 04 / FEATURED PROJECTS', '']
        for project in projects[:4]:
            if project.get('visibility') != 'public':
                raise ValueError('Only verified public projects may be featured')
            name = project['repository']
            if not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', name):
                raise ValueError('Invalid project repository')
            lines += [f"### [{name}](https://github.com/{name})", '', project['description'], '', ' · '.join(project['technologies']), '']
    lines += [
        '## 05 / GITHUB ANALYTICS', '', '<p>',
        f'  <picture><source media="(max-width: 600px)" srcset="{base}github-stats-mobile.svg" /><img src="{base}github-stats.svg" alt="Public activity KPI cards: commits, opened pull requests, current stars and opened issues. Read metric definitions below." width="410" /></picture>',
        f'  <picture><source media="(max-width: 600px)" srcset="{base}languages-mobile.svg" /><img src="{base}languages.svg" alt="Language distribution based on included public repository code size, not proficiency." width="410" /></picture>',
        '</p>', '',
        '<details><summary>Scope and metric definitions</summary>', '',
        '- **Activity window:** the inclusive 365-day UTC interval printed on the cards.',
        '- **Commits:** unique commits authored by this account on default branches of owned public repositories. Forks, archived repositories and this profile repository are excluded. Dates use Git committer timestamps (UTC).',
        '- **Pull Requests / Issues:** public items opened by this account in the same interval; the profile repository is excluded. Reviews and comments are not counted.',
        '- **Stars:** the current star total on the included owned public repositories. This is a lifetime stock, not a 365-day activity count.',
        '- **Languages:** GitHub language byte totals from the included repositories. Notebook/code generation can affect shares. This is not a proficiency score.',
        '- **Privacy:** no private repository names, contents, or activity aggregates are used.',
        '- **Updates:** scheduled around 08:00 JST daily once automation is deployed. Failed updates preserve the last successful images.', '',
        '</details>', '',
        '## 06 / CONTRIBUTION ACTIVITY', '',
        f'<picture><source media="(max-width: 600px)" srcset="{base}contribution-snake-mobile.svg" /><img src="{base}contribution-snake.svg" alt="Gold snake over the real, explicitly scoped public activity calendar: commits, opened pull requests and opened issues. This excludes private activities and is not the native GitHub total." width="1200" /></picture>', ''
    ]
    return '\n'.join(lines)

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--config', type=Path, default=ROOT/'config/profile.json')
    p.add_argument('--generated-branch', help='Use only after the branch has been successfully seeded')
    args = p.parse_args()
    config = json.loads(args.config.read_text(encoding='utf-8'))
    root = args.config.resolve().parent.parent
    about_cards(config, root)
    (root/'README.md').write_text(render(config, args.generated_branch), encoding='utf-8')
    print('English README and About cards generated. No remote changes made.')

if __name__ == '__main__':
    main()
